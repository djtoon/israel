def _next_id(taken):
    """Next free minted S-id: 1000-1499 while free, then 4000+ (1500-1999 helper patches, 2000-2099 city fixes, 3000-3099 omissions)."""
    n = 1000
    while f"S{n}" in taken and n < 1500: n += 1
    if n < 1500 and not (500 <= n < 700): return n
    n = 4000
    while f"S{n}" in taken or 5000 <= n <= 5999: n += 1   # S5000-S5999 reserved for gameplay
    return n

def title_of(url):
    for u in [url]:
        try:
            r = urllib.request.urlopen(urllib.request.Request(u, headers={"User-Agent": "Mozilla/5.0", "Accept-Encoding": "gzip"}), timeout=12)
            raw = r.read()
            if r.headers.get("Content-Encoding") == "gzip": raw = gzip.decompress(raw)
            if raw[:4] == b"%PDF": return None
            m = re.search(rb"<title[^>]*>(.*?)</title>", raw, re.S | re.I)
            if m:
                t = html.unescape(m.group(1).decode("utf-8", "ignore"))
                return re.sub(r"\s+", " ", t).strip()[:200]
        except Exception:
            continue
    return None

def source_for_url(url, hint=None):
    k = nurl(url)
    if k in URLMAP: return URLMAP[k]
    if k not in REG:
        taken = {r["id"] for r in REG.values()} | set(SID) | DELETED_SOURCES
        n = _next_id(taken)
        t = title_of(url)
        dom = re.sub(r"^www\.", "", re.sub(r"^https?://", "", re.sub(r"^https?://web\.archive\.org/web/[^/]+/", "", url)).split("/")[0])
        REG[k] = {"id": f"S{n}", "url": url, "title": t or (hint or url), "domain": dom}
        dump(REG, REG_P)
    r = REG[k]
    if r["id"] not in SID:
        s = {"id": r["id"], "citation": f"{r['domain']}, '{r['title']}'", "url": r["url"] if "web.archive.org" not in r["url"] else None,
             "archived_url": r["url"] if "web.archive.org" in r["url"] else None, "accessed": "2026-10-11", "kind": "web",
             "opened": True, "provenance": "opened", "supports": []}
        S.append(s); SID[s["id"]] = s
    URLMAP[k] = r["id"]
    return r["id"]

def preset_title(url, title):
    """Register a hand-written citation title for a URL before its S-id is minted (no network title lookup)."""
    k = nurl(url)
    if k in URLMAP or k in REG or not title:
        return
    taken = {r["id"] for r in REG.values()} | set(SID) | DELETED_SOURCES
    n = _next_id(taken)
    dom = re.sub(r"^www\.", "", re.sub(r"^https?://", "", re.sub(r"^https?://web\.archive\.org/web/[^/]+/", "", url)).split("/")[0])
    REG[k] = {"id": f"S{n}", "url": url, "title": title, "domain": dom}
    dump(REG, REG_P)

def add_cite(e, claim, sid, quote="", url="", page="", choice=None):
    if sid not in SID:   # explicit minted id (from a published cities.json / fix file) whose source was not created yet
        r = next((v for v in REG.values() if v["id"] == sid), None)
        if r: source_for_url(r["url"])
    c = {"claim": claim, "source": sid}
    if quote: c["quote"] = quote
    if url: c["url"] = url
    if page: c["page"] = page
    tgt = e["cite"] if choice is None else choice.setdefault("cite", [])
    if not any(x.get("source") == sid and x.get("quote") == quote and x.get("claim") == claim for x in tgt):
        tgt.append(c)
    s = SID[sid]
    if claim and claim not in s["supports"] and len(s["supports"]) < 40:
        s["supports"].append(claim)
    if quote or page:
        s["opened"] = True
        if s.get("provenance") != "opened": s["provenance"] = "opened"
        if not s.get("accessed"): s["accessed"] = "2026-10-11"
        if url and "web.archive.org" in url and not s.get("archived_url"): s["archived_url"] = url

