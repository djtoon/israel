def nurl(u):
    u = (u or "").strip()
    u = re.sub(r"^https?://web\.archive\.org/web/[^/]+/", "", u)
    u = re.sub(r"^https?://", "", u).replace("www.", "").rstrip("/")
    return u.lower()

